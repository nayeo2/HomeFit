  await page.getByLabel('만 나이').fill('35')
  await page.getByLabel('혼인 상태').selectOption('single')
  await page.getByLabel('세대 보유 주택 수').fill('0')
  await page.getByLabel('생애 최초 주택 구입 여부').selectOption('yes')
