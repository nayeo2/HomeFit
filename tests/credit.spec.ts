  await page.getByLabel('근로·소득 유형').selectOption('employee')
  await page.getByLabel('본인 연소득').fill('60000000')
  await page.getByLabel('소득 증빙 상태').selectOption('available')
  await page.getByLabel('보유 현금·예금').fill('100000000')
  await page.getByLabel('월 상환 가능 예산').fill('2000000')
  await page.getByRole('button', { name: '다음 · 부채·신용' }).click()
  await page.getByRole('button', { name: '다음 · 주택정보' }).click()
  await expect(page.getByText('신용평가사를 선택해 주세요.')).toBeVisible()
  await page.getByLabel('신용평가사').selectOption('KCB')
  await page.getByLabel('신용점수').fill('800')
  await page.getByLabel('연체 여부').selectOption('no')
  await page.getByLabel('채무조정 여부').selectOption('no')
  await page.getByLabel('기존 대출 여부').selectOption('yes')
  await page.getByRole('button', { name: '다음 · 주택정보' }).click()
  await expect(page.getByText('기존 대출을 하나 이상 추가해 주세요.')).toBeVisible()
  await page.getByRole('button', { name: '대출 추가', exact: true }).click()
  await page.getByLabel('대출 종류').selectOption('creditLine')
  await page.getByLabel('대출 잔액').fill('1000000')
  await page.getByLabel('연이율').fill('4.25')
  await page.getByLabel('남은 기간').fill('12')
  await page.getByLabel('상환 방식').selectOption('bullet')
  await page.getByLabel('대출 한도').fill('2000000')
  await page.getByLabel('신규 주택담보대출 전 전액 상환 예정').selectOption('yes')
  await expect(page.getByLabel('대출 잔액')).toHaveValue('1,000,000')
  await page.getByRole('button', { name: '대출 추가', exact: true }).click()
  await expect(page.getByLabel('대출 종류')).toHaveCount(2)
  await page.getByRole('button', { name: '기존 대출 2 삭제' }).click()
  await page.getByLabel('기존 대출 여부').selectOption('no')
  await expect(page.getByLabel('대출 잔액')).toHaveCount(0)
  await page.getByLabel('기존 대출 여부').selectOption('yes')
  await expect(page.getByLabel('대출 잔액')).toHaveValue('1,000,000')
  await page.getByRole('button', { name: '이전 · 소득·자산' }).click()
  await page.getByRole('link', { name: '3단계 · 부채·신용' }).click()
  await expect(page.getByLabel('대출 잔액')).toHaveValue('1,000,000')
  await page.getByRole('button', { name: '다음 · 주택정보' }).click()
  await expect(page).toHaveURL(/\/diagnosis\/house$/)
  await page.getByRole('link', { name: '3단계 · 부채·신용' }).click()
  await expect(page.getByRole('link', { name: '4단계 · 주택정보' })).toBeVisible()
  await page.getByLabel('신용점수').fill('')
  await expect(page.getByText('4단계 · 주택정보 (잠김)')).toBeVisible()
  await page.getByLabel('신용점수').fill('800')
  await page.getByRole('button', { name: '기존 대출 1 삭제' }).click()
  await page.getByRole('button', { name: '다음 · 주택정보' }).click()
  await expect(page.getByText('기존 대출을 하나 이상 추가해 주세요.')).toBeVisible()
  await page.getByLabel('기존 대출 여부').selectOption('no')
  await page.getByRole('button', { name: '다음 · 주택정보' }).click()
  await expect(page).toHaveURL(/\/diagnosis\/house$/)
  await page.getByLabel('소재지 시·도').fill('서울')
  await page.getByLabel('소재지 시·군·구').fill('강서구')
  await page.getByLabel('주택 유형').fill('아파트')
  await page.getByLabel('매매가격').fill('500000000')
  await page.getByRole('button', { name: '다음 · 대출조건' }).click()
  await page.getByLabel('희망 대출금액').fill('300000000')
  await page.getByLabel('가정 연이율').fill('4')
  await page.getByLabel('대출 기간', { exact: false }).fill('30')
  await page.getByLabel('금리 유형').selectOption('variable')
  await page.getByLabel('상환 방식').selectOption('equalPayment')
  await page.getByRole('button', { name: '다음 · 진단 결과' }).click()
  await expect(page).toHaveURL(/\/diagnosis\/result$/)
  await expect(page.getByRole('heading', { name: '구입 자금', exact: true })).toBeVisible()
  await expect(page.getByText('예상 취득 비용이 입력되지 않아 총비용과 필요자금을 확정할 수 없습니다.').first()).toBeVisible()
  await page.getByRole('tab', { name: '상세', exact: true }).click()
  await expect(page.getByRole('tabpanel', { name: '상세', exact: true }).getByText('규제 LTV 한도', { exact: true })).toBeVisible()
  await expect(page.getByRole('tabpanel', { name: '상세', exact: true }).getByText('스트레스 DSR', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: '시뮬레이션', exact: true }).click()
  await page.getByLabel('시뮬레이션 매매가격').fill('450000000')
  await page.getByLabel('시뮬레이션 희망 대출금액').fill('200000000')
  await page.getByLabel('시뮬레이션 가정 연이율').fill('0')
  await page.getByLabel('시뮬레이션 대출 기간').fill('20')
  const interestRow = page.getByRole('row').filter({ has: page.getByRole('rowheader', { name: '총 이자 (추정)', exact: true }) })
  await expect(interestRow.getByRole('cell').nth(1)).toHaveText('0원')
  await expect(interestRow.getByRole('cell').nth(2)).toContainText('-')
  const needRow = page.getByRole('row').filter({ has: page.getByRole('rowheader', { name: '자기자금 차감 후 필요자금', exact: true }) })
  await expect(needRow.getByRole('cell').nth(1)).toContainText('NEEDS_VERIFICATION')
  await page.getByLabel('시뮬레이션 대출 기간').fill('0')
  await expect(page.getByRole('status')).toContainText('입력값을 확인해 주세요.')
  await expect(page.getByRole('table')).toHaveCount(0)
  await page.getByRole('button', { name: '원본으로 초기화' }).click()
  await expect(page.getByLabel('시뮬레이션 희망 대출금액')).toHaveValue('300,000,000')
  await expect(page.getByLabel('시뮬레이션 가정 연이율')).toHaveValue('4')
  await expect(page.getByLabel('시뮬레이션 대출 기간')).toHaveValue('30')
  await expect(interestRow.getByRole('cell').nth(2)).toHaveText('0원')
  await page.getByRole('tab', { name: '상세', exact: true }).click()
  await expect(page.getByRole('tabpanel', { name: '상세', exact: true }).getByText('300,000,000원', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: '시뮬레이션', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('link', { name: '이전 · 대출조건 수정' }).click()
  await expect(page.getByLabel('희망 대출금액')).toHaveValue('300,000,000')
  await page.getByLabel('가정 연이율').fill('5')
  await expect(page.getByText('6단계 · 진단 결과 (잠김)')).toBeVisible()
  await page.reload()
  await expect(page).toHaveURL(/\/diagnosis\/basic$/)
  await expect(page.getByLabel('만 나이')).toHaveValue('')
