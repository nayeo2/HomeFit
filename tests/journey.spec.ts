import { expect, test } from '@playwright/test'
import { basic, credit, finance, house, loan, results, start, synthetic, usableLayout } from './journey'

test('전체 폼 검증·조건부 입력·탭 키보드와 레이아웃', async ({ page }) => {
  await start(page)
  await usableLayout(page)
  await page.getByRole('button', { name: '다음 · 소득·자산' }).click()
  await expect(page.getByLabel('만 나이')).toHaveAttribute('aria-invalid', 'true')
  await basic(page, true)
  await page.getByRole('button', { name: '다음 · 부채·신용' }).click()
  await expect(page.getByLabel('본인 연소득')).toHaveAttribute('aria-invalid', 'true')
  await page.getByLabel('배우자 연소득').fill('31000123')
  await page.getByLabel('배우자 소득 합산 자격').selectOption('unknown')
  await page.getByLabel('주택 매각 순유입액').fill('71000123')
  await usableLayout(page)
  await finance(page)
  await page.getByRole('link', { name: '1단계 · 기본정보' }).click()
  await page.getByLabel('혼인 상태').selectOption('single')
  await page.getByLabel('세대 보유 주택 수').fill('0')
  await page.getByRole('button', { name: '다음 · 소득·자산' }).click()
  await expect(page.getByLabel('배우자 연소득')).toHaveCount(0)
  await expect(page.getByLabel('주택 매각 순유입액')).toHaveCount(0)
  await page.getByRole('button', { name: '이전 · 기본정보' }).click()
  await page.getByLabel('혼인 상태').selectOption('married')
  await page.getByLabel('세대 보유 주택 수').fill('1')
  await page.getByRole('button', { name: '다음 · 소득·자산' }).click()
  await expect(page.getByLabel('배우자 연소득')).toHaveValue('')
  await expect(page.getByLabel('주택 매각 순유입액')).toHaveValue('')
  await page.getByRole('button', { name: '다음 · 부채·신용' }).click()
  await page.getByRole('button', { name: '다음 · 주택정보' }).click()
  await expect(page.getByLabel('신용점수')).toHaveAttribute('aria-invalid', 'true')
  await credit(page)
  await usableLayout(page)
  await page.getByRole('button', { name: '다음 · 대출조건' }).click()
  await expect(page.getByLabel('매매가격')).toHaveAttribute('aria-invalid', 'true')
  await house(page)
  await page.getByRole('button', { name: '다음 · 진단 결과' }).click()
  await expect(page.getByLabel('희망 대출금액')).toHaveAttribute('aria-invalid', 'true')
  await page.getByLabel('금리 유형').selectOption('mixed')
  await page.getByLabel('고정금리 기간').fill('5')
  await page.getByLabel('금리 유형').selectOption('variable')
  await expect(page.getByLabel('고정금리 기간')).toHaveCount(0)
  await page.getByLabel('금리 유형').selectOption('mixed')
  await expect(page.getByLabel('고정금리 기간')).toHaveValue('')
  await usableLayout(page)
  await loan(page)
  await usableLayout(page)
  const tab = page.getByRole('tab', { name: '개요', exact: true })
  await tab.focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: '상세', exact: true })).toBeFocused()
  await expect(page.getByRole('tab', { name: '상세', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: '시뮬레이션', exact: true })).toBeFocused()
  await usableLayout(page)
})

test('완료 전 결과·후행 경로 직접 접근 차단', async ({ page }) => {
  for (const route of ['finance', 'credit', 'house', 'loan', 'result']) {
    await page.goto(`/diagnosis/${route}`)
    await expect(page).toHaveURL(/\/diagnosis\/basic$/)
  }
  await basic(page)
  // History navigation tests guards without reloading and discarding memory state.
  await page.evaluate(() => { history.pushState(null, '', '/diagnosis/result'); dispatchEvent(new PopStateEvent('popstate')) })
  await expect(page).toHaveURL(/\/diagnosis\/finance$/)
  await finance(page)
  await page.evaluate(() => { history.pushState(null, '', '/diagnosis/loan'); dispatchEvent(new PopStateEvent('popstate')) })
  await expect(page).toHaveURL(/\/diagnosis\/credit$/)
})

for (const [step, label, value] of [
  ['1단계 · 기본정보', '만 나이', '36'],
  ['2단계 · 소득·자산', '본인 연소득', '62000123'],
  ['3단계 · 부채·신용', '신용점수', '812'],
  ['4단계 · 주택정보', '매매가격', '520001237'],
  ['5단계 · 대출조건', '가정 연이율', '5.125'],
] as const) {
  test(`${step} 변경 시 결과 재잠금·초안 보존`, async ({ page }) => {
    await results(page)
    await page.getByRole('link', { name: step, exact: true }).click()
    await page.getByLabel(label, { exact: false }).fill(value)
    await expect(page.getByText('6단계 · 진단 결과 (잠김)')).toBeVisible()
    await page.goBack()
    await expect(page).not.toHaveURL(/\/diagnosis\/result$/)
    await expect(page.getByLabel(label, { exact: false })).toHaveValue(value)
  })
}

test('시뮬레이션 변경·초기화는 원본 입력과 완료 상태를 보존', async ({ page }) => {
  await results(page)
  await page.getByRole('tab', { name: '시뮬레이션', exact: true }).click()
  await page.getByLabel('시뮬레이션 매매가격').fill('410001237')
  await page.getByLabel('시뮬레이션 희망 대출금액').fill('210001239')
  await page.getByLabel('시뮬레이션 가정 연이율').fill('0')
  await page.getByLabel('시뮬레이션 대출 기간').fill('20')
  await usableLayout(page)
  const interest = page.getByRole('row').filter({ has: page.getByRole('rowheader', { name: '총 이자 (추정)', exact: true }) })
  await expect(interest.getByRole('cell').nth(1)).toHaveText('0원')
  await page.getByRole('tab', { name: '상세', exact: true }).click()
  await expect(page.getByRole('tabpanel', { name: '상세', exact: true }).getByText('310,001,239원', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: '시뮬레이션', exact: true }).click()
  await expect(page.getByLabel('시뮬레이션 가정 연이율')).toHaveValue('0')
  await page.getByRole('button', { name: '원본으로 초기화' }).click()
  await expect(page.getByLabel('시뮬레이션 매매가격')).toHaveValue(Number(synthetic.price).toLocaleString('ko-KR'))
  await expect(page.getByLabel('시뮬레이션 희망 대출금액')).toHaveValue(Number(synthetic.principal).toLocaleString('ko-KR'))
  await expect(page.getByLabel('시뮬레이션 가정 연이율')).toHaveValue('4.125')
  await expect(page.getByLabel('시뮬레이션 대출 기간')).toHaveValue('30')
  await page.getByRole('link', { name: '이전 · 대출조건 수정' }).click()
  await expect(page.getByLabel('희망 대출금액')).toHaveValue(Number(synthetic.principal).toLocaleString('ko-KR'))
  await expect(page.getByLabel('가정 연이율')).toHaveValue('4.125')
  await expect(page.getByRole('link', { name: '6단계 · 진단 결과' })).toBeVisible()
  await page.getByRole('link', { name: '4단계 · 주택정보', exact: true }).click()
  await expect(page.getByLabel('매매가격')).toHaveValue(Number(synthetic.price).toLocaleString('ko-KR'))
})
